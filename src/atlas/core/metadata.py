"""Helpers for standardizing ATLAS structure metadata.

These utilities are intentionally kept in a lightweight module: they are used
by database generation, the active-learning workflow, and the standalone
cleanup CLI without importing the AiiDA-based active-learning stack.
"""

import pathlib
from collections import Counter
from uuid import uuid4

import numpy as np
from ase import Atoms

import atlas.core.code_utils as atl_cut

_REMOVE_VALUE = object()

# DFT convergence metadata keys used across conversion, cleanup and filtering.
DFT_SCF_CONVERGED_KEY = 'atl_dft_scf_converged'
DFT_IONIC_CONVERGED_KEY = 'atl_dft_ionic_converged'
DFT_IS_RELAXATION_KEY = 'atl_dft_is_relaxation'
DFT_CONVERGED_KEY = 'atl_dft_converged'
DFT_CONVERGENCE_SOURCE_KEY = 'atl_dft_convergence_source'

DFT_CONVERGENCE_KEYS = (
    DFT_SCF_CONVERGED_KEY,
    DFT_IONIC_CONVERGED_KEY,
    DFT_IS_RELAXATION_KEY,
    DFT_CONVERGED_KEY,
    DFT_CONVERGENCE_SOURCE_KEY,
)


# Mapping of legacy ``mdb_*`` info keys to their current ``atl_*`` names.
_MDB_KEY_MIGRATION = {
    'mdb_struct_type': 'atl_struct_type',
    'mdb_id': 'atl_id',
    'mdb_db_index': 'atl_db_index',
    'mdb_al_step': 'atl_al_step',
}


def _sanitize_info_value(value):
    """Convert a metadata value into an XYZ-serializable object."""
    if callable(value):
        return _REMOVE_VALUE
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, pathlib.Path):
        return str(value)
    if isinstance(value, (set, frozenset, tuple)):
        return list(value)
    return value


def standardize_atoms_info(atoms_list: list[Atoms]) -> list[Atoms]:
    """Ensure every ASE structure has standardized ``atl_*`` info keys.

    Migrates legacy ``mdb_*`` keys to their ``atl_*`` equivalents and ensures
    every structure carries an ``atl_id`` UUID. Legacy keys are removed after
    migration. Called automatically by ``load_database`` so that databases
    generated by older versions of the codebase are transparently upgraded.

    Parameters
    ----------
    atoms_list : list of ase.Atoms
        The list of ASE atoms objects to process.

    Returns
    -------
    list of ase.Atoms
        The updated list with standardized keys in ``info``.
    """
    migrated_count = 0
    sanitized_count = 0

    for struct in atoms_list:
        info = struct.info

        # --- XYZ field sanitization -------------------------------------
        for key in list(info.keys()):
            if not isinstance(key, str):
                info[str(key)] = info.pop(key)
                sanitized_count += 1
                key = str(key)

            sanitized_value = _sanitize_info_value(info[key])
            if sanitized_value is _REMOVE_VALUE:
                del info[key]
                sanitized_count += 1
            elif sanitized_value is not info[key]:
                info[key] = sanitized_value
                sanitized_count += 1

        # --- mdb_* -> atl_* migration -----------------------------------
        for old_key, new_key in _MDB_KEY_MIGRATION.items():
            if old_key in info and new_key not in info:
                info[new_key] = info[old_key]
                del info[old_key]
                migrated_count += 1
            elif old_key in info and new_key in info:
                # Both present, so remove the legacy duplicate.
                del info[old_key]

        # --- UUID standardization ---------------------------------------
        uuid_candidate = (
            info.get('atl_id') or info.get('aiida_uuid') or info.get('unique_id')
        )

        if uuid_candidate:
            struct.info['atl_id'] = str(uuid_candidate)
        else:
            struct.info['atl_id'] = str(uuid4())

        if info.get('atl_al_step') == 0 and info.get('aiida_uuid'):
            struct.info['atl_id'] = str(info['aiida_uuid'])
            del info['aiida_uuid']

        if 'unique_id' in info:
            del info['unique_id']

    if migrated_count > 0:
        atl_cut.custom_print(
            f'Migrated {migrated_count} legacy mdb_* info keys to atl_* '
            f'across {len(atoms_list)} structures.',
            'warn',
        )

    if sanitized_count > 0:
        atl_cut.custom_print(
            f'Sanitized {sanitized_count} non-serializable metadata values '
            f'across {len(atoms_list)} structures.',
            'info',
        )

    return atoms_list


def check_atl_ids(atoms_list: list[Atoms]) -> tuple[list[int], dict[str, int]]:
    """Check for ``atl_id`` keys in info dicts and report missing or repeated IDs.

    Parameters
    ----------
    atoms_list : list of ase.Atoms
        Structures to check.

    Returns
    -------
    tuple
        ``(missing_indices, duplicates)`` where ``missing_indices`` lists the
        positions of structures without an ``atl_id`` and ``duplicates`` maps
        repeated IDs to their occurrence count.
    """
    atl_ids = []
    missing_indices = []

    for i, atoms in enumerate(atoms_list):
        if 'atl_id' in atoms.info:
            atl_ids.append(atoms.info['atl_id'])
        else:
            missing_indices.append(i)

    id_counts = Counter(atl_ids)
    duplicates = {k: v for k, v in id_counts.items() if v > 1}

    return missing_indices, duplicates
